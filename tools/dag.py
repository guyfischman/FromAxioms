def caption_counts(d):
    """The two numbers the page's caption states: declarations, dependencies.

    **One rule, one place.** `figclaims.py` recomputes these to check the
    drawing, and for a while it recomputed them DIFFERENTLY -- `len(rows)` over
    the whole export against this function's root-excluding count, a gap of
    exactly the 13 axiom and principle nodes. Both were internally honest and
    the figure was reported WRONG while rendering the number it meant. That is
    the ledger-parser defect in a new place: one set computed twice, disagreeing
    on the cases nobody looked at.

    The roots are DRAWN; they are not DECLARATIONS, and the caption says
    declarations. Edges out of a root are the picture's frame -- an axiom
    entering the library -- rather than one declaration depending on another.
    """
    roots = {"axiom", "principle"}
    decls = [n for n in d["nodes"] if n["k"] not in roots]
    ax = {i for i, n in enumerate(d["nodes"]) if n["k"] in roots}
    dep_edges = [e for e in d["edges"] if e[0] not in ax]
    return len(decls), len(dep_edges)


def page():
    d = graph()
    if d is None:
        return None
    down = set(a for a, _ in d["edges"])
    lemmas = sum(1 for i, n in enumerate(d["nodes"])
                 if n["k"] == "theorem" and i not in down)
    # Selection, not a drop -- see `caption_counts`, which both this and
    # `figclaims.py` now read the rule from. This reasoning lived in
    # `dropped-allow.txt` until a refactor made that entry stale; it belongs
    # beside the code it explains rather than in a registry row.
    roots = {"axiom", "principle"}
    decls = [n for n in d["nodes"] if n["k"] not in roots]
    ax = {i for i, n in enumerate(d["nodes"]) if n["k"] in roots}
    dep_edges = [e for e in d["edges"] if e[0] not in ax]
    # The interpreter DETECTS a stray `%` in the template and does not LOCATE
    # it: the traceback points at this line, not at the offending character,
    # and finding it means grepping a 300-line template. That happened today
    # over a `%` in a comment about a percentage. So catch and say where
    #. Detection was never the gap.
    try:
        return _render(PAGE, decls, dep_edges, lemmas, d)
    except (TypeError, ValueError) as e:
        import re as _re
        # Consume `%%` pairs FIRST, then look for a survivor. Scanning for
        # `%` not followed by `%` reports the second half of every correctly
        # escaped pair -- `55%% 52%%` came back as two violations, so the
        # diagnostic accused the lines that were already right.
        bad = []
        for i, ln in enumerate(PAGE.splitlines(), 1):
            rest = _re.sub(r"%%", "", ln)
            rest = _re.sub(r"%\([a-z]+\)[sd]", "", rest)
            if "%" in rest:
                bad.append((i, ln))
        if bad:
            where = "\n".join(f"      template line {i}: {ln.strip()[:70]}"
                               for i, ln in bad[:5])
            raise SystemExit(
                f"  dag.py: the page template has {len(bad)} unescaped `%`.\n"
                f"  The whole page is one Python format string, so a literal\n"
                f"  percent must be written `%%` -- in CSS, in JS, and in\n"
                f"  comments alike:\n{where}") from e
        raise


def _render(PAGE, decls, dep_edges, lemmas, d):
    return PAGE % {
        "marker": MARKER,
        "count": len(decls),
        "edges": len(dep_edges),
        "lemmas": lemmas,
        "intro": sum(1 for n in d["nodes"] if n["i"]),
        "land": sum(1 for n in d["nodes"] if n.get("lm")),
        "data": json.dumps(d, separators=(",", ":")),
    }


