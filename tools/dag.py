_SOURCES = {}


def _decl_url(by, name):
    """The published source line declaring `name`, as a link."""
    r = by.get(name)
    if r is None:
        return None
    rel = r["module"].replace(".", "/") + ".lean"
    if rel not in _SOURCES:
        f = ROOT / rel
        _SOURCES[rel] = f.read_text(errors="replace") if f.exists() else None
    text = _SOURCES[rel]
    if text is None:
        return None
    short = name.split(".")[-1]
    m = re.search(
        r"^[ \t]*(?:@\[[^\]]*\][ \t]*)*"
        r"(?:(?:private|protected|noncomputable|partial|unsafe)[ \t]+)*"
        r"(?:theorem|lemma|def|abbrev|structure|class|inductive|instance|axiom|opaque)"
        r"[ \t]+(?:[\w.]*\.)?" + re.escape(short) + r"(?![\w'.])",
        text, re.M)
    line = f"#L{text.count(chr(10), 0, m.start()) + 1}" if m else ""
    return f"{REPO}blob/master/{rel}{line}"


def _core_url(name):
    """`name` in Lean core, at the toolchain's own commit."""
    import subprocess
    try:
        prefix = subprocess.run(["lean", "--print-prefix"], capture_output=True,
                                text=True, cwd=ROOT).stdout.strip()
        version = subprocess.run(["lean", "--version"], capture_output=True,
                                 text=True, cwd=ROOT).stdout
    except OSError:
        return None
    commit = re.search(r"commit ([0-9a-f]{40})", version)
    src = pathlib.Path(prefix) / "src" / "lean"
    if not commit or not src.is_dir():
        return None
    ns, _, short = name.rpartition(".")
    pat = re.compile(r"^[ \t]*(?:theorem|lemma|def|abbrev)[ \t]+"
                     r"(?:" + re.escape(name) + "|" + re.escape(short) + r")(?![\w'.])",
                     re.M)
    for f in sorted((src / "Init").rglob("*.lean")):
        text = f.read_text(errors="replace")
        m = pat.search(text)
        if m and (not ns or f"namespace {ns}" in text or name in m.group(0)):
            line = text.count("\n", 0, m.start()) + 1
            rel = f.relative_to(src).as_posix()
            return (f"https://github.com/leanprover/lean4/blob/{commit.group(1)}"
                    f"/src/{rel}#L{line}")
    return None


def _pairs():
    """Comparator pairs keyed by the landmark rows they match.

    Mathlib links are pinned to the revision `comparator/lake-manifest.json`
    records, and use the `path:line` each pair gives for its statement, so an
    upstream change cannot move what a link points at.
    """
    y = ROOT / "comparator" / "formalization.yaml"
    if not y.exists():
        return {}
    rev = None
    man = ROOT / "comparator" / "lake-manifest.json"
    if man.exists():
        for pkg in json.loads(man.read_text()).get("packages", []):
            if pkg.get("name") == "mathlib":
                rev = pkg.get("rev")
    lines = y.read_text().split("\n")
    starts = [i for i, l in enumerate(lines) if l.startswith("  - id: ")]
    out = {}
    for k, s in enumerate(starts):
        e = starts[k + 1] if k + 1 < len(starts) else len(lines)
        while e > s and not lines[e - 1].strip():
            e -= 1
        blk = "\n".join(lines[s:e])

        def get(key):
            m = re.search(r"^    " + key + r":[ \t]*(.+)$", blk, re.M)
            return m.group(1).strip() if m else None

        pid = lines[s][len("  - id: "):].strip()
        ml, src = get("mathlib"), get("mathlib_source") or ""
        mlu = None
        m = re.match(r"(Mathlib/\S+\.lean):(\d+)$", src)
        if ml and ml.startswith("none"):
            ml = None
        elif m and rev:
            mlu = (f"https://github.com/leanprover-community/mathlib4/blob/"
                   f"{rev}/{m.group(1)}#L{m.group(2)}")
        elif ml and "Lean core" in src:
            mlu = _core_url(ml)
        d = "".join(w[:1].upper() + w[1:] for w in pid.split("-"))
        pair_dir = ROOT / "comparator" / "Comparator" / d
        rec = {"id": pid, "ml": ml, "mlu": mlu,
               "src": "Lean core" if "Lean core" in src else "Mathlib",
               "dir": (f"{REPO}tree/master/comparator/Comparator/{d}"
                       if pair_dir.is_dir() else None),
               "yaml": f"{REPO}blob/master/comparator/formalization.yaml"
                       f"#L{s + 1}-L{e}"}
        for row in re.findall(r'^      - "(.+)"$', blk, re.M):
            out[row] = rec
    return out


def graph():
    """Nodes, edges, layers, and where each axiom first enters."""
    sys.path.insert(0, str(ROOT / "tools"))
    import astexport
    rows = astexport.export(cached_only=True)
    if rows is None:
        return None

    by = {r["name"]: r for r in rows}
    # `d in by` discards any reference the export does not carry. On a
    # complete export that is 0 of 75,470 edges, so the filter looks inert --
    # but a partial export reaches it: with 5% of rows absent it silently
    # drops 2,733 references and simply draws a smaller graph. Nothing else
    # can catch that, because `figclaims.py` recomputes the totals from this
    # same export, so both numbers move together and agree.
    dropped = sum(1 for n, r in by.items()
                  for d in r.get("refs", ()) if d != n and d not in by)
    deps = {n: sorted({d for d in r.get("refs", ()) if d in by and d != n})
            for n, r in by.items()}

    if dropped:
        print(f"  WARNING -- {dropped} reference(s) point at declarations the "
              f"export does not carry; the graph is drawn without them and "
              f"its edge count is an undercount. The export is partial: "
              f"refresh it before reading the picture.")

    # A declaration introduces an axiom when none of its dependencies use it.
    intro = {}
    for n, r in by.items():
        used = set()
        for d in deps[n]:
            used |= set(by[d].get("axioms", ()))
        got = sorted(set(r.get("axioms", ())) - used)
        if got:
            intro[n] = got

    # Longest path from a root. Iterative, since the graph is 6k deep in the
    # worst case and Python's recursion limit is not.
    layer = {n: 0 for n in by}
    for n in _topo(by, deps):
        for d in deps[n]:
            if layer[d] + 1 > layer[n]:
                layer[n] = layer[d] + 1

    names = sorted(by)
    idx = {n: i for i, n in enumerate(names)}
    # The axioms are roots of the picture, not properties of it. Each gets a
    # node at layer -1 and an edge to every declaration that *introduces* it,
    # which is what makes the drawing start where the user's question does:
    # at the kernel's assumptions, with each entering only where first needed.
    # Index order must match the order the root nodes are APPENDED below, not
    # KERNEL's declaration order -- `Classical.choice` is appended last so it
    # sits at the bottom of the rail, and an index computed from KERNEL would
    # point every choice edge at a principle instead.
    ax_idx = {"propext": len(names), "Quot.sound": len(names) + 1}

    # The kernel axioms are not the whole cost structure, and on their own
    # they are the least interesting part of it: `Classical.choice` is what
    # Lean assumes, while `LLPO`, `FAN`, `DC`, `EM` and the rest are what the
    # *mathematics* costs. Those are `Prop` hypotheses rather than axioms, so
    # `#print axioms` cannot see them -- but the elaborated `refs` graph can,
    # because a theorem taking `(h : LLPO)` mentions `LLPO` in its type.
    #
    # So each principle the lattice names, and which is defined here, becomes
    # a root beside the axioms, with an edge to every declaration that names
    # it. That is the minimal-principle reading: what a theorem needs, not
    # merely what the kernel assumed underneath it.
    lat = json.loads((ROOT / "tools" / "lattice.json").read_text())
    want = {n.lower() for n in lat["nodes"]} | {"fan", "wkl", "pathselection"}
    # A STATEMENT PRICED AS A LANDMARK IS A RESULT, NOT A PRINCIPLE. The lattice
    # carries `ExactIVT01` as a node so its place can be computed; on the rail
    # it would read as something other theorems pay for.
    equivs = json.loads((ROOT / "tools" / "classical.json").read_text()) \
        .get("_equivalences", [])
    priced = {e["statement"] for e in equivs if e.get("landmark")}
    cand = {}
    for n in names:
        s = n.split(".")[-1]
        if s.lower() in want and n not in priced:
            cand.setdefault(s.lower(), []).append(n)
    princ = {}
    for key, opts in cand.items():
        # Prefer the one declared in `Omniscience.lean`, then the shallowest
        # name: the principles live there, and a collision like `D0.mp` does
        # not.
        best = sorted(opts, key=lambda n: (
            by[n]["module"].split(".")[-1] != "Omniscience",
            n.count("."), n))[0]
        princ[best.split(".")[-1]] = best
    # A PRINCIPLE NOTHING DEPENDS ON IS NOT DRAWN. The lattice names more
    # principles than any one cut uses, and each was given a root on the rail
    # whether or not a single declaration took it as a hypothesis -- so the
    # picture showed a cost that nothing here pays. A root is where an edge
    # starts; without one it says nothing about this library, and a reader
    # reasonably takes a drawn principle as one something needs.
    users = {s: [n for n in names if full in by[n].get("refs", ()) and n != full]
             for s, full in princ.items()}
    princ = {s: full for s, full in princ.items() if users[s]}
    # STRENGTH ORDER, derived from the lattice's own closure rather than
    # listed by hand. A principle that derives more is stronger; ties keep the
    # alphabetical order so the layout is stable across runs. The kernel
    # axioms bracket it: `propext` and `Quot.sound` are the two Lean assumes
    # without any choice content, and `Classical.choice` is the strongest
    # assumption in the picture -- it proves `em` and `funext`, which neither
    # of the others does. So the rail reads weakest at the top to strongest at
    # the bottom, and an edge's colour is the strongest thing flowing down it.
    edges_l = lat["edges"]

    def _derives(start):
        have, changed = {start}, True
        while changed:
            changed = False
            for e in edges_l:
                pre = e["from"] if isinstance(e["from"], list) else [e["from"]]
                if all(x in have for x in pre) and e["to"] not in have:
                    have.add(e["to"])
                    changed = True
        return have - {start}

    strength = {s: len(_derives(s.lower())) for s in princ}
    ranked = sorted(princ, key=lambda s: (strength[s], s))
    pr_idx = {s: len(names) + 2 + i for i, s in enumerate(ranked)}
    ax_idx["Classical.choice"] = len(names) + 2 + len(ranked)
    nodes = [{
        "n": n.split(".")[-1],
        "f": n,
        "m": by[n]["module"].split(".")[-1],
        "k": by[n]["kind"],
        "l": layer[n],
        "a": [a for a in KERNEL if a in by[n].get("axioms", ())],
        # The PRINCIPLES the statement takes, read off its type. The panel
        # listed kernel axioms alone, so `mvt_lagrange_of_llpo_binaryDC_dc` --
        # whose own name says what it takes -- reported `propext, Quot.sound`
        # and nothing else, while the drawing showed its edges to LLPO,
        # BinaryDC and DC. The edges were right and the panel was incomplete,
        # which is the worse way round: a reader checks the panel.
        "p": sorted({x.split(".")[-1] for x in by[n].get("typeRefs", ())}
                    & set(princ)),
        "i": intro.get(n, []),
        "d": len(deps[n]),
    } for n in names]
    # Landmarks, so the dated results are findable rather than being three
    # of six thousand identical dots.
    sys.path.insert(0, str(ROOT / "tools"))
    # ONE node per dated landmark, not every declaration whose name happens to
    # match a detector. The detectors are regexes over squashed names, so a row
    # like "the mean value theorem" matched dozens of lemmas and the
    # landmarks-only view showed 422 dots named `rec`, `smulFun`, `HasDerivAt`
    # -- declaration names, when what a reader wants is "irrationality of √2".
    #
    # The representative is the most DEPENDED-UPON match: a landmark's headline
    # theorem is the one the rest of the library builds on, and ties break on
    # the shorter name, which is the general statement rather than a variant.
    land = {}
    # THE PUBLISHED LANDMARKS, read from `tools/landmarks.json`.
    #
    # This imported the dating table, which is a research instrument and not
    # part of this tree, inside a `try` that fell back to marking nothing. So
    # the first published graph opened on `only landmarks` over an empty
    # canvas: the failure mode of a missing input that is caught and ignored.
    # Absence is now refused, because a graph with no landmark in it is not a
    # smaller answer to the question a reader came with, it is no answer.
    marks = ROOT / "tools" / "landmarks.json"
    if not marks.exists():
        raise SystemExit(f"missing {marks} -- which landmark a declaration "
                         f"carries is not recoverable from the source alone")
    # ONE NODE PER ROW. A row reached by two witnesses keeps a theorem where
    # there is one, then the more depended-upon.
    rdeg = {}
    for n in names:
        for d in deps[n]:
            rdeg[d] = rdeg.get(d, 0) + 1
    best = {}
    for name, (what, yr) in json.loads(marks.read_text()).items():
        if name not in by:
            continue
        # A theorem before a definition: `sqrtTwoP` is used far more than
        # `sq_two_irrational`, and is the proposition rather than its proof.
        key = (by[name]["kind"] == "theorem", rdeg.get(name, 0), -len(name), name)
        if what not in best or key > best[what][0]:
            best[what] = (key, name, yr)
    land = {name: (what, yr) for what, (_k, name, yr) in best.items()}
    if not land:
        raise SystemExit(f"{marks} names no declaration this tree has")
    # THE BRACKET: what a reversal proves the landmark needs, and what the
    # library's proof of it uses. Only published proofs are cited, so a side
    # with nothing published says so rather than naming a declaration the
    # reader cannot open.
    full_of = {full: s for s, full in princ.items()}
    by_key = {s.lower(): s for s in princ}

    def principles_in(start):
        seen, stack = {start}, [start]
        while stack:
            for d in deps[stack.pop()]:
                if d not in seen:
                    seen.add(d)
                    stack.append(d)
        return sorted({full_of[r] for x in seen for r in by[x].get("refs", ())
                       if r in full_of and r != x})

    def link(s):
        return {"p": s, "pu": _decl_url(by, princ[s])}

    pairs = _pairs()
    for nd in nodes:
        got = land.get(nd["f"])
        # `the` dropped from the front, so an alphabetical list sorts by the
        # result's own name.
        nd["lm"] = (re.sub(r"^the\s+", "", got[0]) + f" ({got[1]})") if got else ""
        nd["yr"] = got[1] if got else None
        if not got:
            continue
        name = nd["f"]
        nd["u"] = _decl_url(by, name)
        entry = next((e for e in equivs
                      if name in (e["statement"], e.get("reversal"), e.get("forward"))),
                     None)
        rev, via, used = [], name, None
        if entry:
            s = by_key.get(entry["principle"].lower())
            if s and entry.get("reversal") in by:
                rev.append({**link(s), "by": entry["reversal"],
                            "bu": _decl_url(by, entry["reversal"])})
            # The forward proof is what USES principles. With it unpublished
            # there is no proof here to read them off, and the statement's own
            # cone would report `none` for a result that needs one.
            via = entry.get("forward") if entry.get("forward") in by else None
            if via:
                used = [link(s) for s in principles_in(via)]
                # Hypotheses the lattice does not draw as principles, which the
                # registry records beside the proof.
                for x in entry.get("extra", []):
                    full = next((n for n in by if n.split(".")[-1] == x), None)
                    if full and x not in {u["p"] for u in used}:
                        used.append({"p": x, "pu": _decl_url(by, full)})
        else:
            used = [link(s) for s in principles_in(name)]
        nd["br"] = {"rev": rev, "used": used, "via": via,
                    "vu": _decl_url(by, via) if via else None}
        if got[0] in pairs:
            nd["pr"] = pairs[got[0]]

    # `r` is the rail rank: weakest at 0. `propext` and `Quot.sound` sit above
    # every principle because Lean assumes them with no choice content;
    # `Classical.choice` sits below every one because it proves `em`, which is
    # the top of the lattice. The principles fill the middle in derived order.
    nodes.append({"n": "propext", "f": "propext", "m": "(kernel axiom)",
                  "k": "axiom", "l": -1, "a": ["propext"], "i": [], "d": 0,
                  "lm": "", "r": 0})
    nodes.append({"n": "Quot.sound", "f": "Quot.sound", "m": "(kernel axiom)",
                  "k": "axiom", "l": -1, "a": ["Quot.sound"], "i": [], "d": 0,
                  "lm": "", "r": 0})
    for i, s in enumerate(ranked):
        nodes.append({"n": s, "f": princ[s], "m": "(principle)",
                      "k": "principle", "l": -1, "a": [], "i": [], "d": 0,
                      "lm": "", "r": i + 1, "u": _decl_url(by, princ[s])})
    nodes.append({"n": "Classical.choice", "f": "Classical.choice",
                  "m": "(kernel axiom)", "k": "axiom", "l": -1,
                  "a": ["Classical.choice"], "i": [], "d": 0, "lm": "",
                  "r": len(ranked) + 1})
    edges = [[idx[d], idx[n]] for n in names for d in deps[n]]
    edges += [[ax_idx[a], idx[n]] for n, got in intro.items() for a in got]
    edges += [[pr_idx[s], idx[n]] for s, full in princ.items()
              for n in names if full in by[n].get("refs", ()) and n != full]
    return {"nodes": nodes, "edges": edges}


def _topo(by, deps):
    """Dependency order, iteratively. Cycles cannot occur in a Lean env."""
    seen, out = set(), []
    for start in by:
        if start in seen:
            continue
        stack = [(start, False)]
        while stack:
            n, done = stack.pop()
            if done:
                out.append(n)
                continue
            if n in seen:
                continue
            seen.add(n)
            stack.append((n, True))
            for d in deps[n]:
                if d not in seen:
                    stack.append((d, False))
    return out


