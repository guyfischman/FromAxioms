#!/usr/bin/env python3
"""The library as a dependency DAG, from the axioms upward.

    python3 tools/dag.py            # what would change
    python3 tools/dag.py --record   # write figures/dag.html
    python3 tools/dag.py --check    # CI: fail if stale or unparseable

The five SVGs answer questions about the *registry*. This answers the one
about the *library*: what is built on what, starting from the axioms Lean's
kernel assumes, with each further axiom entering only where it is first
needed.

**"First needed" is not a metaphor here.** A declaration's axioms are the
union of its dependencies' axioms plus whatever its own proof adds, so a
declaration *introduces* an axiom exactly when it uses one that none of its
dependencies use. 341 of 6196 declarations introduce anything at all, and
only **nine** introduce `Classical.choice` -- so the classical fragment is
not a region of the graph, it is nine entry points and their reachable set,
which turns out to reach almost nothing.

**Why HTML and not another SVG.** The graph has 6196 nodes and 75217 edges.
A static image of that is a smear, and the questions worth asking of it --
what does this rest on, what breaks if this is wrong, where does `choice`
first appear -- are all *navigation*. So this emits a self-contained page:
layered layout computed here, drawn on a canvas, with pan, zoom, search, a
lemma toggle, and click-to-trace back to the axioms.

The layering is a longest path from a root, so a node sits above everything
it depends on and adding an edge moves the picture rather than requiring it
to be redrawn -- the same rule the lattice figure uses.
"""

